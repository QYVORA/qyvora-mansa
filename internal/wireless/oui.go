// VendorFromBSSID extracts the OUI and looks it up.
func VendorFromBSSID(bssid string) string {
	bssid = strings.ToUpper(strings.TrimSpace(bssid))
	if len(bssid) < 8 {
		return "Unknown"
	}
	oui := bssid[:8]
	if v, ok := ouiMap[oui]; ok {
		return v
	}
	return "Unknown"
}
